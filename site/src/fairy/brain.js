// Greek-friendly normalisation: lowercase, strip accents/diaeresis, final sigma, punctuation
export function norm(s) {
  return s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/ς/g, 'σ')
    .replace(/[^a-z0-9α-ω\s]/g, ' ').replace(/\s+/g, ' ').trim();
}

