export function answer(text) {
  const q = ` ${norm(text)} `;
  const words = q.trim().split(' ').filter(Boolean);
  let best = null, bestScore = 0;
  for (const it of INTENTS) {
    let sc = 0;
    for (const k of it.keys) {
      const nk = norm(k);
      if (k.startsWith('=')) { if (words.includes(nk)) sc += 1; continue; }        // exact word
      if (nk.includes(' ')) { if (q.includes(' ' + nk)) sc += 3; continue; }         // phrase
      if (words.some(w => w.startsWith(nk))) sc += 1;                                // prefix
    }
    if (it.urgent && sc) sc += 2.5;           // safety first
    if (sc > bestScore) { best = it; bestScore = sc; }
  }
  if (!best) return {
    a: `Αυτό δεν το ξέρω σίγουρα, και δεν θέλω να σας πω κάτι λάθος. Οι γιατροί θα σας απαντήσουν με χαρά στο ${PHONE}.`,
    action: call, unknown: true
  };
  return best;
}
